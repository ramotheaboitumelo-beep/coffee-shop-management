
const mongoose = require("mongoose");

const menuSchema = new mongoose.Schema({
    id: {
        type: String,
        required: true,
        unique: true
    },
    name: {
        type: String,
        required: true,
        trim: true
    },
    description: {
        type: String,
        required: true,
        trim: true
    },
    category: {
        type: String,
        required: true,
        trim: true
    },
    price: {
        type: Number,
        required: true,
        min: 0.01
    },
    available: {
        type: Boolean,
        default: true
    }
});

module.exports = mongoose.model("Menu", menuSchema);
